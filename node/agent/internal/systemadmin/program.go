package systemadmin

import (
	"errors"
	"fmt"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

// Third-party program management: an owner-placed executable under
// /usr/local/lib/nassimhub-programs/<name>/, run as its own locked system
// user inside a sandboxed unit with an explicit resource envelope. Everything
// here is pure validation and generation; the filesystem and systemctl work is
// in program_linux.go. The rules exist so that nothing a request carries can
// become a path traversal or a unit-file injection.

var programName = regexp.MustCompile(`^[a-z][a-z0-9-]{0,20}$`)

const (
	programUnitPrefix = "nassimhub-program-"
	programUserPrefix = "nassimhub-p-"
	programBinRoot    = "/usr/local/lib/nassimhub-programs"
	programDataRoot   = "/var/lib/nassimhub-programs"

	// Resource envelope defaults and clamps, sized for a 379 MiB device that
	// must keep the modem, calls and the administration working.
	programDefaultMemoryMiB = 64
	programMinMemoryMiB     = 16
	programMaxMemoryMiB     = 256
	programDefaultCPUWeight = 20
	programDefaultTasksMax  = 64
	programMaxTasks         = 256
	programMinTasks         = 16
	programMaxArgs          = 32
	programMaxArgBytes      = 256
)

// validateProgramRequest checks one program action. install demands the full
// request; remove only the name.
func validateProgramRequest(r *ProgramRequest, install bool) error {
	if r == nil {
		return errors.New("program request is missing")
	}
	if !programName.MatchString(r.Name) {
		return errors.New("program name must be 1-21 chars of [a-z0-9-], starting with a letter")
	}
	if !install {
		if len(r.ExecStart) > 0 || r.Description != "" || r.MemoryMaxMiB != 0 || r.CPUWeight != 0 || r.TasksMax != 0 {
			return errors.New("program_remove takes only a name")
		}
		return nil
	}
	if len(r.ExecStart) == 0 || len(r.ExecStart) > programMaxArgs {
		return fmt.Errorf("exec_start must be 1-%d arguments", programMaxArgs)
	}
	for _, argument := range r.ExecStart {
		if argument == "" || len(argument) > programMaxArgBytes || strings.ContainsAny(argument, "\x00\n\r\t") {
			return errors.New("exec_start arguments must be 1-256 bytes without control characters")
		}
	}
	if len(r.Description) > 120 || strings.ContainsAny(r.Description, "\x00\n\r") {
		return errors.New("description must be at most 120 bytes on one line")
	}
	binary := filepath.Clean("/" + r.ExecStart[0])
	if !strings.HasPrefix(binary, programBinRoot+"/"+r.Name+"/") {
		return fmt.Errorf("the executable must live under %s/%s/", programBinRoot, r.Name)
	}
	if r.MemoryMaxMiB == 0 {
		r.MemoryMaxMiB = programDefaultMemoryMiB
	}
	if r.CPUWeight == 0 {
		r.CPUWeight = programDefaultCPUWeight
	}
	if r.TasksMax == 0 {
		r.TasksMax = programDefaultTasksMax
	}
	if r.MemoryMaxMiB < programMinMemoryMiB || r.MemoryMaxMiB > programMaxMemoryMiB {
		return fmt.Errorf("memory_max_mib must be %d-%d on this device", programMinMemoryMiB, programMaxMemoryMiB)
	}
	if r.CPUWeight < 1 || r.CPUWeight > 100 {
		return errors.New("cpu_weight must be 1-100")
	}
	if r.TasksMax < programMinTasks || r.TasksMax > programMaxTasks {
		return fmt.Errorf("tasks_max must be %d-%d", programMinTasks, programMaxTasks)
	}
	return nil
}

// programUser is the locked system user one program runs as.
func programUser(name string) string { return programUserPrefix + name }

// programUnit is the unit name one program is managed under.
func programUnit(name string) string { return programUnitPrefix + name + ".service" }

// programUnitText renders the sandboxed unit. Every directive is generated,
// never taken from the request: a program cannot widen its own sandbox, and a
// crash-looping program is stopped by the start limit rather than taking the
// device down.
func programUnitText(r ProgramRequest) string {
	name, user := r.Name, programUser(r.Name)
	data := programDataRoot + "/" + name
	description := r.Description
	if description == "" {
		description = "nassimhub third-party program " + name
	}
	var exec strings.Builder
	for index, argument := range r.ExecStart {
		if index > 0 {
			exec.WriteByte(' ')
		}
		exec.WriteString(strconv.Quote(argument))
	}
	return fmt.Sprintf(`# Generated by nassimhub-system-admin; edit nothing here: reinstall the program instead.
[Unit]
Description=%s
Documentation=file:///etc/nassimhub/system-admin/SYSTEM-ADMIN.md
After=network-online.target
Wants=network-online.target
# A program that keeps failing is stopped, never allowed to wedge the device.
StartLimitIntervalSec=300
StartLimitBurst=5

[Service]
Type=simple
User=%s
Group=%s
ExecStart=%s
WorkingDirectory=%s
Restart=on-failure
RestartSec=5s
# Resource envelope chosen by the owner, clamped at install time.
MemoryMax=%dM
MemorySwapMax=0
CPUWeight=%d
TasksMax=%d
# Untrusted code gets the strict profile. A program that needs more must not be
# installed through this manager.
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectClock=yes
ProtectHostname=yes
RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
MemoryDenyWriteExecute=yes
CapabilityBoundingSet=
AmbientCapabilities=
SystemCallFilter=@system-service
SystemCallErrorNumber=EPERM
UMask=0077
ReadWritePaths=%s
StandardOutput=journal
StandardError=journal
SyslogIdentifier=%s

[Install]
WantedBy=multi-user.target
`, description, user, user, exec.String(), data, r.MemoryMaxMiB, r.CPUWeight, r.TasksMax, data, programUnitPrefix+name)
}
